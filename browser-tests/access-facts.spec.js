import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('Beacon access facts stay grouped through mobile details, copy, print, Saved and reload', async ({ page }, info) => {
  await page.setViewportSize({ width: 320, height: 740 });
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.__accessCopy = text; } } });
    window.print = () => { window.__accessPrint = true; };
  });
  const failures = [];
  const maps = [];
  page.on('pageerror', error => failures.push(error.message));
  page.on('request', request => { if (/maps\.apple\.com|www\.google\.com\/maps/.test(request.url())) maps.push(request.url()); });
  await page.goto('/service/beacon-houston');
  const facts = page.locator('[data-service-before-you-go]');
  const breakfast = facts.locator('[data-service-route="breakfast"]');
  await expect(breakfast).toContainText('Caroline Street');
  await expect(breakfast).toContainText('America/Chicago');
  await expect(breakfast).toContainText('7–9:30 a.m.');
  await expect(facts.locator('[data-service-route="housing-assessment"]')).toContainText('first 25 people');
  await expect(facts.locator('[data-service-route="showers-laundry"]')).toContainText('does not publish shower or laundry end times');
  await expect(facts).toContainText('do not confirm space, stock or admission');
  const nextBreakfast = breakfast.getByRole('link', { name: 'Directions to breakfast', exact: true });
  await expect(nextBreakfast).toBeVisible();
  expect(new URL(await nextBreakfast.getAttribute('href')).searchParams.get('destination')).toBe('1212 Prairie Street, Houston, TX 77002');
  expect((await nextBreakfast.boundingBox()).height).toBeGreaterThanOrEqual(44);
  await expect(breakfast.getByRole('link', { name: /Housing assessment intake details/ })).toHaveCount(0);
  await expect(facts.locator('[data-service-route="housing-assessment"]').getByRole('link', { name: 'Housing assessment intake details', exact: true })).toHaveAttribute('href', 'https://www.beaconhomeless.org/gethelp');
  await expect(page.locator('.service-next-steps').getByRole('link', { name: /^Choose service access/ })).toHaveAttribute('href', '#before-you-go-title');
  await expect(page.locator('.service-next-steps a[href*="google.com/maps"]')).toHaveCount(0);
  const breakfastDirections = breakfast.getByRole('link', { name: 'Directions to breakfast', exact: true });
  await expect(breakfastDirections).toBeVisible();
  expect(new URL(await breakfastDirections.getAttribute('href')).searchParams.get('destination')).toBe('1212 Prairie Street, Houston, TX 77002');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.locator('[data-service-copy]').click();
  const copied = await page.evaluate(() => window.__accessCopy);
  expect(copied).toContain('Breakfast\nAccess location: 1212 Prairie Street');
  expect(copied).toContain('Entrance: Day Center entrance on Caroline Street');
  expect(copied).toContain('Housing assessment intake\nAccess location:');
  expect(copied).toContain('first 25 people');
  expect(copied).toContain('no live capacity confirmation');
  await page.locator('[data-service-print]').click();
  expect(await page.evaluate(() => window.__accessPrint)).toBe(true);
  await page.emulateMedia({ media: 'print' });
  await expect(breakfast).toBeVisible();
  await expect(breakfast).toContainText('Caroline Street');
  await page.emulateMedia({ media: 'screen' });
  await breakfast.getByRole('heading', { name: 'Breakfast', exact: true }).scrollIntoViewIfNeeded();
  await info.attach('beacon-before-you-go-320', { body: await page.screenshot(), contentType: 'image/png' });
  await page.locator('[data-service-save]').click();
  await page.getByRole('link', { name: 'View saved services', exact: true }).click();
  const saved = page.locator('[data-saved-services] .directory-global-result-wrap').filter({ has: page.locator('a[href="/service/beacon-houston"]') });
  await expect(saved).toContainText('Caroline Street');
  await expect(saved).toContainText('first 25 people');
  await expect(saved).toContainText('America/Chicago');
  await page.reload();
  await expect(saved).toContainText('Caroline Street');
  await expect(saved).toContainText('first 25 people');
  expect(failures).toEqual([]);
  expect(maps).toEqual([]);
});

test('an address-only service provides the reviewed destination without a fictional globe point', async ({ page }) => {
  await page.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function (type, ...args) { return /webgl/i.test(type) ? null : original.call(this, type, ...args); };
  });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/service/taunton-community-table-meals');
  const facts = page.locator('[data-service-before-you-go]');
  await expect(facts).toContainText('no paperwork or ID');
  await expect(facts).toContainText('Last Thursday of each month');
  await expect(facts.locator('[data-service-route="weekday-lunch"]').getByRole('link', { name: 'Directions to weekday lunch', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Show on interactive globe', exact: true })).toHaveCount(0);
  await expect(page.locator('.service-next-steps a[href^="/#resource="]')).toHaveCount(0);
  const directions = facts.locator('[data-service-route="weekday-lunch"]').getByRole('link', { name: 'Directions to weekday lunch', exact: true });
  expect(new URL(await directions.getAttribute('href')).searchParams.get('destination')).toBe('378 Bay Street, Taunton, MA 02780');
  await page.goto('/');
  await expect(page.locator('html')).toHaveAttribute('data-finder-startup', 'ready');
  await page.locator('#resourceSearch').fill('Taunton');
  const card = page.locator('.resource-card[data-result-resource-id="taunton-community-table-meals"]');
  await expect(card).toBeVisible();
  await expect(card.locator('.result-access-facts')).toContainText('no paperwork or ID');
  await expect(card.locator('.result-access-facts')).toContainText('Last Thursday of each month');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
