import { mkdir, writeFile } from "node:fs/promises";
import { resources, curatedResources } from "../src/data/resources.js";
import {
  canonical,
  fingerprint,
  fetchPublishedCatalog,
  assertFreshExport,
  summarizeCatalogDrift,
} from "./catalog-sync-core.mjs";

// Explicit operations only: builds never silently publish or overwrite database edits.
const action = process.argv[2];
if (action === "seed") {
  await mkdir("supabase/import", { recursive: true });
  for (let offset = 0; offset < resources.length; offset += 100) {
    const records = resources.slice(offset, offset + 100);
    const values = records
      .map(
        (r) =>
          `('${r.id.replaceAll("'", "''")}', '${JSON.stringify(r).replaceAll("'", "''")}'::jsonb)`,
      )
      .join(",\n");
    // Re-running a bootstrap import must never overwrite an editor's work.
    await writeFile(
      `supabase/import/catalog-${String(offset / 100).padStart(3, "0")}.sql`,
      `insert into public.rwn_locations(id, record) values\n${values}\non conflict (id) do nothing;\n`,
    );
  }
  console.log(
    `Prepared ${resources.length} source-backed locations. SHA-256 ${fingerprint(resources)}`,
  );
} else if (action === "verify" || action === "export") {
  const url =
    process.env.SUPABASE_URL || "https://cytfrxldixdapjaxcqzf.supabase.co";
  const key =
    process.env.SUPABASE_PUBLISHABLE_KEY ||
    "sb_publishable_QcjZr9DWdhMW42P8HK33mQ_cvu1S0ut";
  const records = await fetchPublishedCatalog({ url, key });
  if (action === "export") {
    if (!records.length)
      throw new Error(
        "Refusing to export an empty catalog. Investigate the database first.",
      );
    assertFreshExport(records, curatedResources);
    const base = new Map(
      curatedResources.map((r) => [r.id, JSON.stringify(canonical(r))]),
    );
    const remoteIds = new Set(records.map((r) => r.id));
    const overrides = records
      .filter((r) => base.get(r.id) !== JSON.stringify(canonical(r)))
      .sort((a, b) => a.id.localeCompare(b.id));
    const withheld = curatedResources
      .filter((r) => !remoteIds.has(r.id))
      .map((r) => r.id)
      .sort();
    await writeFile(
      "src/data/generated/editorial-overrides.js",
      `// Generated by npm run catalog:export. Review this diff before releasing.\nexport const editorialOverrides = ${JSON.stringify(overrides, null, 2)};\nexport const withheldLocationIds = ${JSON.stringify(withheld, null, 2)};\n`,
    );
    console.log(
      `Exported ${overrides.length} edited/new records and ${withheld.length} withheld IDs. Run npm run check, review the diff, then release.`,
    );
    process.exit(0);
  }
  const local = fingerprint(resources.map(canonical));
  const remote = fingerprint(records.map(canonical));
  if (local !== remote) {
    const { releaseOnly, databaseOnly, changed } = summarizeCatalogDrift(resources, records);
    const describe = ({ count, sample }) => count + (sample.length
      ? ` (sample: ${sample.join(", ")})` : "");
    console.error(`Catalog drift: release source ${resources.length}/${local}; public database ${records.length}/${remote}.`);
    console.error(`Release only: ${describe(releaseOnly)}; database only: ${describe(databaseOnly)}; changed shared IDs: ${describe(changed)}.`);
    console.error("Read-only preflight: nothing changed. Reconcile against reviewed source and editorial history before release.");
    process.exitCode = 1;
  } else {
    console.log(
      `Verified all ${records.length} database records match the globe and directory catalog. SHA-256 ${remote}`,
    );
  }
} else throw new Error("Use: node scripts/catalog-sync.mjs seed|verify|export");
