import test from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { checkRepositoryArtifacts, findTrackedArtifacts } from "../scripts/check-repository-artifacts.mjs";

test("artifact guard distinguishes generated paths from authored assets and snapshots", () => {
  assert.deepEqual(findTrackedArtifacts([
    "dist/index.html", "node_modules/package/index.js", "tools/node_modules/helper/index.js",
    "qa-screenshots/directory.png", "qa-cross-browser/results.json", "playwright-report/index.html", "test-results/error.png",
    "src/data/generated/resources.js", "public/media/earth.jpg", "tests/fixtures/service.json",
    "docs/dist-notes.md", "package-lock.json",
  ]), ["dist/index.html", "node_modules/package/index.js", "tools/node_modules/helper/index.js", "qa-screenshots/directory.png", "qa-cross-browser/results.json", "playwright-report/index.html", "test-results/error.png"]);
});

test("artifact guard rejects force-added ignored files and accepts index-only removal", () => {
  const cwd = mkdtempSync(join(tmpdir(), "rwn-artifact-guard-"));
  const git = (...args) => execFileSync("git", args, { cwd, stdio: "pipe" });
  try {
    git("init", "--quiet");
    writeFileSync(join(cwd, ".gitignore"), "dist/\n");
    writeFileSync(join(cwd, "index.html"), "authored source");
    mkdirSync(join(cwd, "dist"));
    writeFileSync(join(cwd, "dist/index.html"), "generated bytes");
    git("add", ".gitignore", "index.html");
    assert.equal(checkRepositoryArtifacts(cwd), 2);
    git("add", "--force", "dist/index.html");
    assert.throws(() => checkRepositoryArtifacts(cwd), /dist\/index.html/);
    git("rm", "--cached", "dist/index.html");
    assert.equal(checkRepositoryArtifacts(cwd), 2);
    assert.equal(readFileSync(join(cwd, "dist/index.html"), "utf8"), "generated bytes");
    assert.equal(readFileSync(join(cwd, "index.html"), "utf8"), "authored source");
  } finally {
    rmSync(cwd, { recursive: true, force: true });
  }
});
